async def main():
    os.makedirs(OUT, exist_ok=True)
    for k, h, t in S:
        await edge_tts.Communicate(t, VOICE, rate=RATE).save(f"{OUT}/{k}.mp3")
        print("saved", k)
    json.dump([{"k": k, "h": h, "t": t} for k, h, t in S], open(f"{OUT}/scripts.json", "w", encoding="utf8"), ensure_ascii=False, indent=1)

asyncio.run(main())
