async def main():
    import sys
    os.makedirs(OUT, exist_ok=True)
    only = sys.argv[1:]  # 예: python tools/mk_cap31_voice.py s05  → 그 칸만 다시 만든다
    for k, t in S.items():
        if only and k not in only:
            continue
        await edge_tts.Communicate(t, VOICE, rate=RATE).save(f"{OUT}/{k}.mp3")
        print("saved", k)

asyncio.run(main())
