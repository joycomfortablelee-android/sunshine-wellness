def grid(cols, rows_spec, header=None, h=28, exact=True):
    t = table(cols)
    if header:
        row(t, [{'text': x, 'size': 8.5, 'bold': True, 'color': NAVY, 'bg': HEAD_BG,
                 'align': CENTER} for x in header], h=14)
    for r in rows_spec:
        cells = []
        for i, x in enumerate(r):
            if i == 0 and isinstance(x, str) and x.startswith('#'):
                cells.append({'text': x[1:], 'size': 8.5, 'bold': True, 'color': NAVY,
                              'bg': 'F7F9FC', 'valign': TOP})
            elif isinstance(x, str) and x.startswith('~'):
                cells.append({'text': x[1:], 'size': 8.0, 'color': GRAY, 'valign': TOP})
            else:
                cells.append({'text': x, 'size': 9.0, 'valign': TOP})
        row(t, cells, h=h, exact=exact)
    spacer(4)
    return t


